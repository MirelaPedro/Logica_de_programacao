#include <stdio.h>

int main()
{
    printf("Tamanho do int: %i\n", sizeof(int));
    printf("Tamanho do float: %i\n", sizeof(float));
    printf("Tamanho do char: %i\n", sizeof(char));
    printf("Tamanho do double: %i\n", sizeof(double));
    
    return 0;
}

